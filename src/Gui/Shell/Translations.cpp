/// Schlägt jeden Text im Wörterbuch nach, unabhängig vom Qt-Kontext (so greift es auch bei Befehlsnamen und Tooltips)
class Translator: public QTranslator
{
public:
    QString translate(const char*, const char* source, const char*, int) const override
    {
        return source ? Gui::Shell::german(source) : QString();
    }
    bool isEmpty() const override
    {
        return false;
    }
};

ParameterGrp::handle general()
{
    return App::GetApplication().GetParameterGroupByPath("User parameter:BaseApp/Preferences/General");
}

